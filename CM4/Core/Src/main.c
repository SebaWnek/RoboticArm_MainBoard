void UART3_WriteChar(char c)
{
    /* Wait until TX register is empty */
    while (!(USART3->ISR & USART_ISR_TXE_TXFNF))
    {
    }

    USART3->TDR = (uint8_t)c;
}

void UART3_WriteBuffer(const char *data, int len)
{
    for (int i = 0; i < len; i++)
    {
        while (!(USART3->ISR & USART_ISR_TXE_TXFNF))
        {
        }

        USART3->TDR = (uint8_t)data[i];
    }
}

